export function getLocalizedCropName(crop: string, lang: LanguageCode = 'en'): string {
  if (!crop) return '';
  const match = CROP_LOCALIZED_NAMES[crop];
  if (match && match[lang]) {
    return match[lang];
  }
  // Try case-insensitive matching
  for (const [key, map] of Object.entries(CROP_LOCALIZED_NAMES)) {
    if (key.toLowerCase() === crop.toLowerCase() || crop.toLowerCase().includes(key.toLowerCase())) {
      return map[lang] || key;
    }
  }
  return crop;
}

